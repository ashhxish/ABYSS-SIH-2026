/* ------------------------------------------------------------------ *
 * 7. Candidate vessel analysis (follows the console's selected candidate)
 * ------------------------------------------------------------------ */
function buildCandidate(investigation, entry, timeline) {
  if (!entry) {
    return emptySection('candidate', 'Candidate vessel analysis', 'No candidate is currently selected.', {
      selected: { value: true, basis: 'No candidate is currently selected.' },
    })
  }
  const behaviour = entry.behaviour || {}
  const gap = entry.gapAnalysis || {}
  const compatibility = entry.compatibility || {}
  const filters = compatibility.filters || {}
  const events = Array.isArray(timeline?.events) ? timeline.events : []
  const vesselEvents = events.filter(
    (event) => event.scope === 'vessel' && String(event.mmsi) === String(entry.mmsi),
  )
  const gaps = Array.isArray(gap.gaps) ? gap.gaps : []

  return section('candidate', 'Candidate vessel analysis', true, {
    selectedMmsi: entry.mmsi,
    mmsi: fact('MMSI', entry.mmsi, { source: 'ranking.entries[].mmsi' }),
    vesselId: fact('Vessel identifier', entry.vesselId, { source: 'ranking.entries[].vesselId' }),
    name: fact('Vessel name', entry.name, { source: 'ranking.entries[].name' }),
    vesselType: fact('Vessel type', entry.vesselType, { source: 'ranking.entries[].vesselType' }),
    rank: fact('Candidate rank', entry.rank, {
      source: 'ranking.entries[].rank',
      format: (v) => `#${fmtInt(v)}`,
    }),
    totalScore: fact(SCORE_LABEL, entry.totalScore, {
      source: 'ranking.entries[].totalScore',
      format: (v) => `${fmtNumber(v, 3)} / 100`,
    }),
    distanceToSlickKm: fact('Distance to the observed slick', entry.distanceToSlickKm, {
      source: 'ranking.entries[].distanceToSlickKm',
      format: fmtKm,
    }),
    weights: investigation?.weights
      ? { available: true, value: investigation.weights, source: 'investigation.weights' }
      : { available: false, value: null, source: 'investigation.weights' },
    passedFilters: {
      available: Object.keys(filters).length > 0,
      value: filters,
      source: 'ranking.entries[].compatibility.filters',
    },
    factors: factorRows(entry.factors).map((row) => ({
      ...row,
      display: row.available ? `${fmtNumber(row.points, 3)} / ${fmtNumber(row.maxPoints, 0)}` : '—',
      source: `ranking.entries[].factors.${row.key}`,
    })),
    reasons: Array.isArray(entry.reasons) ? entry.reasons : [],
    reasonsSource: 'ranking.entries[].reasons (engine wording, unmodified)',
    compatibility: {
      minDistanceKmDuringWindow: fact('Closest approach during the release window', compatibility.minDistanceKmDuringWindow, {
        source: 'ranking.entries[].compatibility.minDistanceKmDuringWindow',
        format: fmtKm,
      }),
      minDistanceKmWholeTrack: fact('Closest approach over the whole track', compatibility.minDistanceKmWholeTrack, {
        source: 'ranking.entries[].compatibility.minDistanceKmWholeTrack',
        format: fmtKm,
      }),
      insideRegionDuringWindow: fact('Inside the origin region during the window', compatibility.insideRegionDuringWindow, {
        source: 'ranking.entries[].compatibility.insideRegionDuringWindow',
      }),
      recordsInWindow: fact('AIS reports inside the window', compatibility.recordsInWindow, {
        source: 'ranking.entries[].compatibility.recordsInWindow',
        format: fmtInt,
      }),
      plausibleSegmentFraction: fact('In-window segments within the movement cap', compatibility.plausibleSegmentFraction, {
        source: 'ranking.entries[].compatibility.plausibleSegmentFraction',
        format: (v) => `${Math.round(v * 100)}%`,
      }),
      speedCapKn: fact('Movement cap used for this vessel', compatibility.speedCapKn, {
        source: 'ranking.entries[].compatibility.speedCapKn',
        format: (v) => `${fmtNumber(v, 2)} kn`,
      }),
    },
    behaviour: {
      available: Boolean(behaviour.mmsi),
      rawAnomaly: fact('Behavioural anomaly (raw, versus own baseline)', behaviour.rawAnomaly, {
        source: 'ranking.entries[].behaviour.rawAnomaly',
        format: (v) => fmtNumber(v, 3),
      }),
      isAnomaly: fact('Flagged as a behavioural anomaly', behaviour.isAnomaly, {
        source: 'ranking.entries[].behaviour.isAnomaly',
      }),
      scoredEligible: fact('Eligible to contribute a behaviour factor', behaviour.scoredEligible, {
        source: 'ranking.entries[].behaviour.scoredEligible',
      }),
      description: fact('Engine description', behaviour.description, {
        source: 'ranking.entries[].behaviour.description',
      }),
      baselineMedianSog: fact('Own-baseline median SOG', behaviour.baseline?.medianSogKn, {
        source: 'ranking.entries[].behaviour.baseline.medianSogKn',
        format: (v) => `${fmtNumber(v, 1)} kn`,
      }),
      windowMedianSog: fact('Window median SOG', behaviour.window?.medianSogKn, {
        source: 'ranking.entries[].behaviour.window.medianSogKn',
        format: (v) => `${fmtNumber(v, 1)} kn`,
      }),
      events: vesselEvents.map((event) => ({
        id: event.id,
        title: text(event.title),
        status: text(event.status),
        at: event.at,
        description: text(event.description),
        source: text(event.source),
        metrics: Array.isArray(event.metrics)
          ? event.metrics.map((metric) => ({ label: text(metric.label), value: text(metric.value) }))
          : [],
      })),
      eventsSource: 'timeline.events (Phase 16 builder), filtered to this vessel',
      notes: list(behaviour.notes),
    },
    gaps: {
      available: gaps.length > 0,
      hasGap: fact('AIS gap present', gap.hasGap, { source: 'ranking.entries[].gapAnalysis.hasGap' }),
      items: gaps.map((g) => ({
        start: g.start,
        end: g.end,
        durationHours: num(g.durationHours),
        straightLineKm: num(g.straightLineKm),
        impliedSpeedKn: num(g.impliedSpeedKn),
        feasible: g.feasible,
        overlapsWindow: g.overlapsWindow,
        relevance: num(g.relevance),
        reasons: Array.isArray(g.reasons) ? g.reasons : [],
        source: 'ranking.entries[].gapAnalysis.gaps[]',
      })),
      itemsSource: 'ranking.entries[].gapAnalysis.gaps[]',
      contextNote:
        "AIS gaps are contextual evidence only. A gap on its own does not raise a vessel's priority: relevance " +
        'requires overlap with the release window, proximity to the origin region and physical feasibility.',
      notes: list(gap.notes),
    },
    counterfactual: {
      available: Boolean(text(entry.counterfactual?.text)),
      text: fact('Counterfactual comparison', entry.counterfactual?.text, {
        source: 'ranking.entries[].counterfactual.text',
        unavailable: 'The engine returned no counterfactual comparison for this candidate.',
      }),
      againstName: text(entry.counterfactual?.againstName),
      source: 'ranking.entries[].counterfactual',
    },
  })
}

/* ------------------------------------------------------------------ *
 * 8 + 9. Timeline and evidence-chain summaries (reused, never rebuilt)
 * ------------------------------------------------------------------ */
function buildTimelineSection(timeline, entry) {
  const events = Array.isArray(timeline?.events) ? timeline.events : []
  const untimed = Array.isArray(timeline?.untimed) ? timeline.untimed : []
  const range = timelineRange(timeline)
  const mmsi = entry?.mmsi
  return section('timeline', 'Investigation timeline', Boolean(timeline), {
    eventCount: events.length,
    untimedCount: untimed.length,
    /** Scope split, so a reader can tell case-level from vessel-level events. */
    counts: {
      case: events.filter((event) => event.scope === 'case').length,
      vessel: events.filter((event) => event.scope === 'vessel').length,
      selectedVessel: mmsi == null ? 0 : events.filter((event) => event.scope === 'vessel' && String(event.mmsi) === String(mmsi)).length,
    },
    vesselEvents:
      mmsi == null ? [] : events.filter((event) => event.scope === 'vessel' && String(event.mmsi) === String(mmsi)),
    range: { available: Boolean(range), value: range, source: 'timeline.js timelineRange(timeline)' },
    statusCounts: {
      available: events.length > 0,
      value: countByStatus(timeline),
      source: 'timeline.js countByStatus(timeline)',
    },
    events: events.map((event) => ({
      id: event.id,
      scope: event.scope,
      title: text(event.title),
      status: text(event.status),
      at: event.at,
      end: event.end,
      description: text(event.description),
      source: text(event.source),
      metrics: Array.isArray(event.metrics)
        ? event.metrics.map((metric) => ({ label: text(metric.label), value: text(metric.value) }))
        : [],
    })),
    untimed: untimed.map((event) => ({
      id: event.id,
      title: text(event.title),
      status: text(event.status),
      description: text(event.description),
      source: text(event.source),
    })),
    source: 'timeline.events (Phase 16 builder)',
  })
}

function buildChain(chain) {
  const layers = Array.isArray(chain?.layers) ? chain.layers : []
  const nodes = Array.isArray(chain?.nodes) ? chain.nodes : []
  const edges = Array.isArray(chain?.edges) ? chain.edges : []
  return section('chain', 'Evidence-chain summary', Boolean(chain), {
    nodeCount: nodes.length,
    edgeCount: edges.length,
    layerCount: layers.length,
    layers: layers.map((layer) => ({
      id: layer.id,
      title: layer.title,
      caption: layer.caption,
      nodeCount: layer.nodes?.length || 0,
      nodes: (layer.nodes || []).map((node) => ({
        id: node.id,
        title: node.title,
        status: node.status,
        source: node.source,
        available: node.available !== false,
        unavailableReason: node.unavailableReason || null,
      })),
    })),
    factors: (chain?.factors || []).map((factor) => ({
      id: factor.id,
      title: factor.title,
      source: factor.source,
      summary: factor.summary,
      available: factor.available !== false,
    })),
    narrative: text(chain?.narrative),
    source: 'evidence chain (Phase 17 builder)',
  })
}

/* ------------------------------------------------------------------ *
 * 10. Confidence summary - separate dimensions, only what the API sent
 * ------------------------------------------------------------------ */
/**
 * Each confidence dimension is labelled and sourced independently. A dimension
 * the API does not publish is reported as unavailable with an explicit status
 * label; it is never replaced by an average of the other dimensions.
 */
const confidenceDimension = (key, label, value, { source, format, unavailable }) => {
  const base = fact(label, value, { source, format, unavailable })
  return {
    key,
    label,
    ...base,
    statusLabel: base.available ? 'Reported by the API' : 'Not provided by the API',
    unavailableNote: base.available ? null : base.unavailable,
  }
}

function buildConfidence(investigation, detection) {
  const dimensions = [
    confidenceDimension('detection', 'Oil-detection confidence', detection?.detectionConfidence, {
      source: 'detection.detectionConfidence',
      format: fmtConfidence,
    }),
    confidenceDimension('origin', 'Origin-reconstruction confidence', investigation?.origin?.region?.confidence, {
      source: 'investigation.origin.region.confidence',
      format: fmtConfidence,
    }),
    confidenceDimension('aisEvidence', 'AIS evidence confidence', null, {
      source: 'not present in the Phase 13 API response',
      unavailable: 'The API does not publish a separate AIS-evidence confidence value; none is shown.',
    }),
    confidenceDimension('overall', 'Overall investigation confidence', null, {
      source: 'not present in the Phase 13 API response',
      unavailable: 'The API does not publish an overall investigation confidence value; none is shown.',
    }),
  ]
  return section('confidence', 'Confidence summary', true, {
    dimensions,
    note:
      'The dimensions are reported separately and are deliberately not averaged. The prototype computes ' +
      'detection and origin confidence only; no combined figure is published by the API.',
  })
}

/* ------------------------------------------------------------------ *
 * 11 + 12. Limitations and methodology / disclaimer
 * ------------------------------------------------------------------ */
function buildLimitations(investigation, detection) {
  /**
   * Each limitation is a plain sentence. Provenance travels beside the list in
   * `itemSources` (positionally aligned) rather than inside the sentence, so the
   * text can be rendered, printed and exported directly.
   */
  const items = []
  const itemSources = []
  const push = (sentence, source) => {
    items.push(sentence)
    itemSources.push(source)
  }
  const synthetic = investigation?.synthetic ?? detection?.synthetic
  if (synthetic || text(investigation?.datasetLabel) || text(detection?.datasetLabel)) {
    push(
      'The AIS and environmental records used here are a synthetic demonstration dataset. They are not real-world ' +
        'observations and are not evidence about any real vessel.',
      'investigation.synthetic / investigation.datasetLabel',
    )
  }
  push(
    'The console map is a local schematic projection (no external map provider), so distances and shapes on screen are illustrative; reported distances are computed geodesically.',
    'frontend rendering (Phase 14/15 map panel)',
  )
  push(
    'Look-alike screening is a heuristic screen over the bundled field, not a validated classifier. A negative screen does not establish that a formation is petroleum.',
    'detection.lookAlikeAssessment',
  )
  push(
    'Compatibility scoring uses prototype factor weights configured for this investigation. The weights are not scientifically validated and are configurable.',
    'investigation.weights',
  )
  push(
    'The probable origin region and release window are model outputs with uncertainty. The region is a probability-density area, not a point estimate, and the release window is a prior supplied with the case rather than derived from the slick alone.',
    'investigation.origin',
  )
  push(
    "A behavioural anomaly describes deviation from a vessel's own observed baseline and is not evidence of wrongdoing.",
    'ranking.entries[].behaviour',
  )
  push(
    'AIS gaps are contextual observations. Absence of an AIS gap is not evidence either, and the physical feasibility of movement across a gap is an estimate based on the observed endpoints only.',
    'ranking.entries[].gapAnalysis',
  )
  const unavailable = ['detection', 'ais', 'candidate', 'timeline', 'chain'].filter(
    (key) => investigation?.[key] === null || investigation?.[key] === undefined,
  )
  return section('limitations', 'Limitations', true, {
    items,
    itemSources,
    unavailableSections: unavailable,
    provenanceNote: 'Every limitation above is also enforced or exposed elsewhere in the console and the API response.',
  })
}

function buildMethodology(investigation) {
  const weights = investigation?.weights
  return section('methodology', 'Methodology and disclaimer', true, {
    pipeline: [
      'Satellite observation',
      'Oil-slick characterisation and look-alike screening',
      'Backward drift (hindcast) to a probable origin region and release window',
      'Historical AIS cleaning and trajectory construction',
      'Spatial, temporal and trajectory compatibility filtering',
      'Behavioural anomaly assessment against a vessel\'s own baseline',
      'AIS-gap analysis with physical-feasibility checks',
      'Explainable evidence scoring and candidate ranking',
    ],
    pipelineSource: 'investigation pipeline (see docs/methodology.md); described, not re-executed here',
    weights: {
      available: Boolean(weights),
      value: weights || null,
      source: 'investigation.weights',
      note: weights ? 'Prototype weights for this run; configurable, not scientifically validated.' : null,
    },
    terminology:
      'Scores are reported as investigation priority / compatibility. Candidate ranking expresses evidence compatibility ' +
      'for analyst review and is not a determination of responsibility.',
    disclaimer: REPORT_DISCLAIMER,
  })
}

/* ------------------------------------------------------------------ *
 * Assembly
 * ------------------------------------------------------------------ */
export function buildInvestigationReport({ investigation, detection, cleaning, timeline, chain, selectedMmsi } = {}) {
  const entries = investigation?.ranking?.entries || []
  const entry = entries.find((candidate) => String(candidate.mmsi) === String(selectedMmsi)) || null

  const sections = [
    buildCase(investigation, detection),
    buildObservation(detection),
    buildLookAlike(detection),
    buildOrigin(investigation),
    buildEnvironment(investigation),
    buildAis(investigation, cleaning),
    buildCandidate(investigation, entry, timeline),
    buildTimelineSection(timeline, entry),
    buildChain(chain),
    buildConfidence(investigation, detection),
    buildLimitations(investigation, detection),
    buildMethodology(investigation),
  ]

  return {
    reportId: `${investigation?.caseId || 'CASE'}-REPORT`,
    caseId: investigation?.caseId || null,
    status: entries.length > 0 ? STATUS.COMPLETE : STATUS.EMPTY,
    generatedFrom: {
      investigation: Boolean(investigation),
      detection: Boolean(detection),
      aisCleaning: Boolean(cleaning),
      timeline: Boolean(timeline),
      evidenceChain: Boolean(chain),
    },
    selectedMmsi: entry?.mmsi ?? null,
    selectedVesselId: entry?.vesselId ?? null,
    selectedRank: entry?.rank ?? null,
    disclaimer: REPORT_DISCLAIMER,
    scoreLabel: SCORE_LABEL,
    sections,
  }
}

export function reportSummaryLines(report) {
  if (!report) return []
  return report.sections
    .filter((section) => section.available)
    .map((section) => section.title)
}
