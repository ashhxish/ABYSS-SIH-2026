/**
 * Phase 18 - automated forensic investigation report.
 *
 * This module is a *formatter*, not a second analysis engine. It reads the
 * payloads the console already holds (the Phase 13 API responses) plus the two
 * existing derived structures - the Phase 16 timeline and the Phase 17 evidence
 * chain - and lays them out as an investigator-facing document.
 *
 * Rules this file obeys:
 *   - nothing is re-scored, re-ranked or re-derived here;
 *   - no value is invented: a field the API did not send is reported as
 *     unavailable, with the reason, rather than filled in;
 *   - every value keeps a provenance label naming the API path it came from;
 *   - the report follows the selected candidate, so it updates when the
 *     investigator selects a different vessel.
 */

import { factorRows, fmtConfidence, fmtDateTime, fmtInt, fmtKm, fmtNumber } from './format.js'
import { countByStatus, timelineRange } from './timeline.js'

/** The methodology statement required of every report, plus the API's own. */
export const REPORT_DISCLAIMER =
  'This report presents evidence compatibility and investigation priority generated by the ABYSS prototype. ' +
  'It does not establish legal responsibility or causation.'

/** Fixed label for the 0-100 number, so no rendering can phrase it as a probability. */
export const SCORE_LABEL = 'investigation priority (compatibility score, 0-100)'

/** Status vocabulary for the report header. */
export const STATUS = Object.freeze({
  COMPLETE: 'Investigation complete - evidence aggregation for analyst review',
  PARTIAL: 'Investigation incomplete - some sources did not load',
  EMPTY: 'No investigation loaded',
})

const num = (value) => (typeof value === 'number' && Number.isFinite(value) ? value : null)

const text = (value) => (typeof value === 'string' && value.trim() !== '' ? neutralizeVocabulary(value.trim()) : null)

/**
 * Booleans are legitimate evidence in their own right (`synthetic: true`,
 * `insideRegionDuringWindow: false`), so they must survive normalisation.
 * Only `undefined` and `null` mean "not provided".
 */
const bool = (value) => (typeof value === 'boolean' ? value : null)

const list = (value) => (Array.isArray(value) ? value.filter((v) => text(v)) : [])

/**
 * The report has its own vocabulary rule: it may never use causality wording,
 * even when quoting another layer. The Phase 16 timeline narrates its scoring
 * step with a negated phrase ("not a probability of responsibility"), which is
 * accurate but still puts the words in a forensic document. Rewriting happens
 * here, at the formatting boundary, so no upstream builder is modified and the
 * numbers and meanings are untouched.
 */
const NEUTRAL_PHRASES = [
  // Longest phrases first, so the specific phrase wins over its substrings.
  [/probability of responsibility/gi, 'statement of responsibility'],
  [/probability of guilt/gi, 'statement of responsibility'],
  [/confirmed responsible/gi, 'identified for review'],
  [/proven criminal/gi, 'identified for review'],
  [/guaranteed source/gi, 'candidate source'],
  [/\bculprit\b/gi, 'candidate vessel'],
  [/\bguilty\b/gi, 'flagged for review'],
]

/**
 * Rewrites causality vocabulary so the forensic document never contains it,
 * even when quoting another layer. The substitution is unconditional: a
 * negated upstream sentence ("... is not a probability of responsibility")
 * becomes "... is not a statement of responsibility", which preserves its
 * meaning while satisfying the report's vocabulary rule. Numbers and
 * measurements are untouched - only the surrounding words change.
 *
 * Exported so the report test can assert this boundary rule directly.
 */
export function neutralizeVocabulary(value) {
  if (typeof value !== 'string') return value
  return NEUTRAL_PHRASES.reduce((acc, [pattern, replacement]) => acc.replace(pattern, replacement), value)
}

/** A value the API supplied, or an explicit "not provided" marker. */
function fact(label, value, { source, format = null, unavailable = 'Not provided by the API response.' } = {}) {
  const raw = num(value) ?? bool(value) ?? text(value)
  if (raw == null) return { label, value: null, display: '—', available: false, unavailable, source }
  const display = format ? format(raw) : typeof raw === 'boolean' ? (raw ? 'Yes' : 'No') : String(raw)
  return { label, value: raw, display, available: true, unavailable: null, source }
}

const section = (id, title, available, data, unavailableReason = null) => ({
  id,
  title,
  available,
  unavailableReason,
  data: available ? data : null,
})

/**
 * A section that cannot be populated still carries a body, so the report view
 * can always say *why* it is empty instead of rendering a blank card.
 */
const emptySection = (id, title, unavailableReason, data = null) => ({
  id,
  title,
  available: false,
  unavailableReason,
  data,
})

/* ------------------------------------------------------------------ *
 * 1. Case identification
 * ------------------------------------------------------------------ */
function buildCase(investigation, detection) {
  const entries = investigation?.ranking?.entries || []
  const loaded = Boolean(investigation)
  return section('case', 'Case identification', loaded, {
    caseId: fact('Case ID', investigation?.caseId, { source: 'investigation.caseId' }),
    status: {
      value: loaded && entries.length > 0 ? STATUS.COMPLETE : STATUS.EMPTY,
      basis:
        loaded && entries.length > 0
          ? `${entries.length} ranked vessels returned by the pipeline.`
          : 'No ranked vessels were returned by the pipeline.',
    },
    observationTime: fact('Observation time', investigation?.observedAt ?? detection?.acquisitionTime, {
      source: 'investigation.observedAt (fallback: detection.acquisitionTime)',
      format: fmtDateTime,
    }),
    acquisitionTime: fact('Satellite acquisition time', detection?.acquisitionTime, {
      source: 'detection.acquisitionTime',
      format: fmtDateTime,
    }),
    datasetLabel: fact('Dataset label', investigation?.datasetLabel ?? detection?.datasetLabel, {
      source: 'investigation.datasetLabel',
    }),
    uiLabel: fact('UI mode label', detection?.uiLabel, { source: 'detection.uiLabel' }),
    synthetic: fact('Synthetic data flag', investigation?.synthetic, { source: 'investigation.synthetic' }),
    module: fact('Intelligence module', investigation?.module, { source: 'investigation.module' }),
    moduleVersion: fact('Module version', investigation?.moduleVersion, { source: 'investigation.moduleVersion' }),
  }, 'No investigation loaded.')
}

/* ------------------------------------------------------------------ *
 * 2 + 3. Satellite observation and look-alike assessment
 * ------------------------------------------------------------------ */
function buildObservation(detection) {
  const available = Boolean(detection)
  const slick = detection?.characterisation || {}
  const bbox = slick.boundingBox || {}
  return section('observation', 'Satellite observation', available, {
    classification: fact('Slick classification', detection?.classification, { source: 'detection.classification' }),
    detected: fact('Slick detected', detection?.detected, { source: 'detection.detected' }),
    acquisitionTime: fact('Acquisition time', detection?.acquisitionTime, {
      source: 'detection.acquisitionTime',
      format: fmtDateTime,
    }),
    sensor: fact('Sensor', detection?.sensor?.name, { source: 'detection.sensor.name' }),
    sensorBand: fact('Sensor band', detection?.sensor?.band, { source: 'detection.sensor.band' }),
    detectionConfidence: fact('Detection confidence', detection?.detectionConfidence, {
      source: 'detection.detectionConfidence',
      format: fmtConfidence,
    }),
    confidenceNote: text(detection?.detectionConfidenceNote),
    centroidLat: fact('Slick centroid latitude', slick.centroid?.lat, {
      source: 'detection.characterisation.centroid.lat',
      format: (v) => fmtNumber(v, 4),
    }),
    centroidLon: fact('Slick centroid longitude', slick.centroid?.lon, {
      source: 'detection.characterisation.centroid.lon',
      format: (v) => fmtNumber(v, 4),
    }),
    areaKm2: fact('Slick area', slick.areaKm2, {
      source: 'detection.characterisation.areaKm2',
      format: (v) => `${fmtNumber(v, 2)} km²`,
    }),
    perimeterKm: fact('Slick perimeter', slick.perimeterKm, { source: 'detection.characterisation.perimeterKm', format: fmtKm }),
    lengthKm: fact('Approximate length', slick.approximateLengthKm, { source: 'detection.characterisation.approximateLengthKm', format: fmtKm }),
    widthKm: fact('Approximate width', slick.approximateWidthKm, { source: 'detection.characterisation.approximateWidthKm', format: fmtKm }),
    orientationDeg: fact('Orientation', slick.orientationDeg, {
      source: 'detection.characterisation.orientationDeg',
      format: (v) => `${fmtNumber(v, 1)}°`,
    }),
    vertexCount: fact('Polygon vertices', slick.vertexCount, { source: 'detection.characterisation.vertexCount', format: fmtInt }),
    boundingBox:
      num(bbox.minLat) != null && num(bbox.maxLat) != null
        ? {
            available: true,
            label: 'Bounding box',
            value: `${fmtNumber(bbox.minLat, 3)} – ${fmtNumber(bbox.maxLat, 3)} lat / ${fmtNumber(bbox.minLon, 3)} – ${fmtNumber(bbox.maxLon, 3)} lon`,
            display: `${fmtNumber(bbox.minLat, 3)} – ${fmtNumber(bbox.maxLat, 3)} lat / ${fmtNumber(bbox.minLon, 3)} – ${fmtNumber(bbox.maxLon, 3)} lon`,
            unavailable: null,
            source: 'detection.characterisation.boundingBox',
          }
        : fact('Bounding box', null, { source: 'detection.characterisation.boundingBox' }),
    geometry: fact('Geometry type', slick.geometry?.type, { source: 'detection.characterisation.geometry.type' }),
    geometryFacts: [
      fact('Geometry type', slick.geometry?.type, { source: 'detection.characterisation.geometry.type' }),
      fact('Polygon vertices', slick.geometry?.coordinates?.[0]?.length, {
        source: 'detection.characterisation.geometry.coordinates[0].length',
        format: fmtInt,
      }),
      fact('Rings', slick.geometry?.coordinates?.length, {
        source: 'detection.characterisation.geometry.coordinates.length',
        format: fmtInt,
      }),
      fact('Coordinate order', 'lon, lat (GeoJSON)', { source: 'detection.characterisation.geometry' }),
    ],
    rawGeometry: slick.geometry || null,
    geometrySource: 'detection.characterisation.geometry (GeoJSON Polygon)',
    warnings: list(detection?.warnings),
  })
}

